#!/usr/bin/env python3
"""Generate the plain-C ARC_GRI30_NOx22 chemistry core from gri30_skel43.yaml.

ARC_GRI30_NOx22 (see the technical report): 22 transported (ODE) species and
21 quasi-steady (QSS) radicals of the 43-species / 262-reaction skeletal
GRI-Mech 3.0 set. The QSS radicals come from a linearized QSSA solve at every
rate evaluation: reaction directions with one QSS reactant are linear in it,
the 11 bimolecular QSS-QSS directions are dropped from the radical balances
(but kept in the final rates of progress). The resulting 21x21 linear system
is solved by dense LU with partial pivoting (numerically the same as the
report's symbolic elimination).

Writes arc_gri30_nox22_data.h (tables) next to this script; the code that
uses them is arc_gri30_nox22.c / .h (hand written).

Usage: python3 gen_arc.py [gri30_skel43.yaml]
"""
import os
import sys

import cantera as ct

HERE = os.path.dirname(os.path.abspath(__file__))
ODE = ("H2 H O O2 OH H2O HO2 H2O2 CH4 CH3 CO CO2 CH2O CH3OH C2H2 C2H4 C2H6 "
       "N2 NO NO2 N2O HCN").split()
QSS = ("C CH CH2 CH2(S) HCO CH2OH CH3O C2H3 C2H5 HCCO N NH NH2 NNH HNO CN "
       "H2CN HCNO HOCN HNCO NCO").split()


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "gri30_skel43.yaml")
    g = ct.Solution(path)
    order = ODE + QSS
    assert sorted(order) == sorted(g.species_names), "species set mismatch"
    idx = {s: i for i, s in enumerate(order)}
    NS = len(order)
    L = []
    w = L.append
    w("/* Generated by gen_arc.py from %s - do not edit */" % os.path.basename(path))
    w("#define ARC_NODE %d" % len(ODE))
    w("#define ARC_NQSS %d" % len(QSS))
    w("#define ARC_NSP %d" % NS)
    w("#define ARC_NR %d" % g.n_reactions)
    w("static const char* arc_names[ARC_NSP] = {%s};" % ", ".join('"%s"' % s for s in order))
    w("static const double arc_W[ARC_NSP] = {%s};" %
      ", ".join("%.10g" % g.molecular_weights[g.species_index(s)] for s in order))
    # elements C H O N per species
    els = ["C", "H", "O", "N"]
    w("static const double arc_el[ARC_NSP][4] = {%s};" % ", ".join(
        "{%s}" % ",".join("%g" % g.n_atoms(s, e) for e in els) for s in order))
    # NASA7: Tmid, high[7], low[7]
    rows = []
    for s in order:
        th = g.species(s).thermo
        c = th.coeffs
        assert len(c) == 15
        rows.append("{%s}" % ",".join("%.12e" % v for v in c))
    w("static const double arc_nasa[ARC_NSP][15] = {\n%s};" % ",\n".join(rows))
    # reactions
    rtype, rev, nr, ri, rn, npr, pi, pn = [], [], [], [], [], [], [], []
    A, b, E, A0, b0, E0, troe, ntroe = [], [], [], [], [], [], [], []
    effs = []
    for r in g.reactions():
        assert not r.orders
        t = r.reaction_type
        ty = {"Arrhenius": 0, "three-body-Arrhenius": 1, "falloff-Troe": 2,
              "falloff-Lindemann": 3}[t]
        rtype.append(ty)
        rev.append(1 if r.reversible else 0)
        re = sorted(r.reactants.items(), key=lambda kv: idx[kv[0]])
        pr = sorted(r.products.items(), key=lambda kv: idx[kv[0]])
        assert len(re) <= 3 and len(pr) <= 3
        nr.append(len(re)); npr.append(len(pr))
        ri.append([idx[k] for k, _ in re] + [0] * (3 - len(re)))
        rn.append([float(v) for _, v in re] + [0.0] * (3 - len(re)))
        pi.append([idx[k] for k, _ in pr] + [0] * (3 - len(pr)))
        pn.append([float(v) for _, v in pr] + [0.0] * (3 - len(pr)))
        if ty in (0, 1):
            k = r.rate
            A.append(k.pre_exponential_factor); b.append(k.temperature_exponent)
            E.append(k.activation_energy)
            A0.append(0.0); b0.append(0.0); E0.append(0.0)
        else:
            hi, lo = r.rate.high_rate, r.rate.low_rate
            A.append(hi.pre_exponential_factor); b.append(hi.temperature_exponent)
            E.append(hi.activation_energy)
            A0.append(lo.pre_exponential_factor); b0.append(lo.temperature_exponent)
            E0.append(lo.activation_energy)
        fc = list(r.rate.falloff_coeffs) if ty == 2 else []
        ntroe.append(len(fc))
        troe.append(fc + [0.0] * (4 - len(fc)))
        e = [1.0] * NS
        if ty in (1, 2, 3):
            tb = r.third_body
            d = tb.default_efficiency
            e = [d] * NS
            for k, v in tb.efficiencies.items():
                e[idx[k]] = v
            # explicit colliders (e.g. H + O2 + O2) come as default efficiency 0
        effs.append(e)
    def arr(name, typ, vals, fmt):
        w("static const %s %s[ARC_NR] = {%s};" % (typ, name, ",".join(fmt % v for v in vals)))
    def arr3(name, typ, vals, fmt):
        w("static const %s %s[ARC_NR][3] = {%s};" % (
            typ, name, ",".join("{%s}" % ",".join(fmt % x for x in v) for v in vals)))
    arr("arc_rtype", "int", rtype, "%d")
    arr("arc_rev", "int", rev, "%d")
    arr("arc_nr", "int", nr, "%d")
    arr("arc_np", "int", npr, "%d")
    arr3("arc_ri", "int", ri, "%d")
    arr3("arc_rn", "double", rn, "%g")
    arr3("arc_pi", "int", pi, "%d")
    arr3("arc_pn", "double", pn, "%g")
    arr("arc_A", "double", A, "%.12e")
    arr("arc_b", "double", b, "%.12e")
    arr("arc_E", "double", E, "%.12e")
    arr("arc_A0", "double", A0, "%.12e")
    arr("arc_b0", "double", b0, "%.12e")
    arr("arc_E0", "double", E0, "%.12e")
    arr("arc_ntroe", "int", ntroe, "%d")
    w("static const double arc_troe[ARC_NR][4] = {%s};" % ",".join(
        "{%s}" % ",".join("%.12e" % x for x in v) for v in troe))
    w("static const double arc_eff[ARC_NR][ARC_NSP] = {%s};" % ",\n".join(
        "{%s}" % ",".join("%g" % x for x in v) for v in effs))
    out = os.path.join(HERE, "arc_gri30_nox22_data.h")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", out, NS, "species", g.n_reactions, "reactions")


if __name__ == "__main__":
    main()
