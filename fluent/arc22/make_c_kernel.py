"""Translate Javier's C++17 ARC_GRI30_NOx22 header (mechanisms/arc_gri30_nox22/original/arc_gri30_nox22.hpp)
into plain C99 for Fluent's UDF compiler (C only). Pure text substitution; the arithmetic is untouched.

    python fluent/arc22/make_c_kernel.py   ->   fluent/arc22/udf/arc22_kernel.c
"""
import pathlib, re

here = pathlib.Path(__file__).resolve().parent
src = (here.parents[1] / "mechanisms/arc_gri30_nox22/original/arc_gri30_nox22.hpp").read_text()

body = src[src.index("namespace arc_gri30_nox22 {") + len("namespace arc_gri30_nox22 {"):
           src.index("inline std::array<double, N_ODE> evaluate_qss(")]
body = body.replace("inline constexpr std::size_t N_ODE = 22;", "")
body = body.replace("inline constexpr std::size_t N_QSS = 21;", "")
body = body.replace("inline constexpr std::size_t N_SPECIES_SKEL = 43;", "")
body = body.replace("inline constexpr double R_GAS", "#define ARCK_R_GAS_VALUE\nstatic const double R_GAS")
body = body.replace("inline constexpr double P_ATM", "static const double P_ATM")
body = body.replace("inline constexpr double", "static const double")
body = body.replace("inline void thermo_ode_cp_h(", "void arck_thermo_cp_h(")
body = body.replace("inline void evaluate_qss(", "void arck_wdot(")
body = body.replace(") noexcept {", ") {")
body = body.replace("double* __restrict__ c_qss_out = nullptr,", "double* ARCK_RESTRICT c_qss_out,")
body = body.replace("const bool project = true", "const int project")
body = body.replace("__restrict__", "ARCK_RESTRICT")
body = body.replace("nullptr", "NULL")
body = body.replace("std::size_t", "int")
body = re.sub(r"std::(exp|log|fmax)\b", r"\1", body)
body = body.replace("#define ARCK_R_GAS_VALUE\n", "")
assert "std::" not in body and "constexpr" not in body and "inline" not in body, "untranslated C++ left"

out = f'''/* ARC_GRI30_NOx22 rate kernel in plain C (22 ODE + 21 LQSSA species).
 * GENERATED by fluent/arc22/make_c_kernel.py from mechanisms/arc_gri30_nox22/original/arc_gri30_nox22.hpp
 * (Javier's deliverable header). Do not edit by hand: change the header and run the script again.
 *
 *   arck_wdot(T, c[22], wdot[22], cqss[21] or NULL, project)
 *       molar production rates [kmol/m3/s] of the 22 ODE species from their concentrations [kmol/m3];
 *       project != 0 applies the header's rate-level element projection (the UDF passes 0 and projects Y).
 *   arck_thermo_cp_h(T, cp[22], h[22])   molar cp [J/kmol/K] and h [J/kmol] of the 22 ODE species.
 */
#include <math.h>
#include <stddef.h>
#include "arc22_kernel.h"

#if defined(__GNUC__) || defined(__clang__)
#define ARCK_RESTRICT __restrict__
#else
#define ARCK_RESTRICT
#endif
{body}'''
(here / "udf/arc22_kernel.c").write_text(out)
(here / "udf/arc22_kernel.h").write_text('''/* ARC_GRI30_NOx22 plain-C rate kernel, see arc22_kernel.c (generated). */
#ifndef ARC22_KERNEL_H
#define ARC22_KERNEL_H
#define ARCK_N_ODE 22
#define ARCK_N_QSS 21
void arck_wdot(const double T, const double* c_ode, double* wdot_ode, double* c_qss_out, const int project);
void arck_thermo_cp_h(const double T, double* cp_mole, double* h_mole);
#endif
''')
print("wrote", here / "udf/arc22_kernel.c")
